#!/usr/bin/env node
// Generates types/index.d.ts (TypeScript types of every schema) with json-schema-to-typescript. Deterministic.
// Usage:
//   node scripts/types.js          write types/index.d.ts
//   node scripts/types.js --check  exit 1 if the file differs from what would be written
//
// Every schema file becomes one named type (typeNameOf). A $ref to another file becomes a reference to that
// file's type, so no type is declared twice. Conditional rules (if/then/else, allOf of conditionals) cannot
// be expressed as plain types and are dropped, except the type → payload branches of chain/entry.json, which
// become the ChainEntry discriminated union.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { posix, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const SCHEMAS_DIR = resolve(ROOT, 'schemas');
export const TYPES_FILE = resolve(ROOT, 'types', 'index.d.ts');

const DIRECTORY_ORDER = ['common', 'entities', 'chain', 'api'];
const ENTRY_PATH = 'chain/entry';
const ENTRY_FIELDS_TYPE = 'ChainEntryFields';

const BANNER = `// Generated by scripts/types.js from schemas/**/*.json. Do not edit; run: npm run types
//
// The types describe the shape only. Patterns, ranges, formats and the conditional rules of the schemas
// (e.g. "lat_e7 and lng_e7 are both set or both null") are checked by schema validation, not by these types.
`;

const pascal = (s) => s.split(/[-._]/).map((w) => w[0].toUpperCase() + w.slice(1)).join('');

/** TypeScript type name of a schema, from its path under schemas/ without .json (e.g. chain/payload-scan → ScanPayload). */
export function typeNameOf(path) {
  const [dir, base] = path.split('/');
  if (path === 'api/error') return 'ErrorResponse';
  if (path === ENTRY_PATH) return 'ChainEntry';
  if (dir === 'chain') return `${pascal(base.replace(/^payload-/, ''))}Payload`;
  return pascal(base);
}

/** Schema paths under schemas/ without .json, in output order. */
export function schemaPaths() {
  return readdirSync(SCHEMAS_DIR, { recursive: true })
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.split('\\').join('/').replace(/\.json$/, ''))
    .sort((a, b) => DIRECTORY_ORDER.indexOf(a.split('/')[0]) - DIRECTORY_ORDER.indexOf(b.split('/')[0]) || (a < b ? -1 : a > b ? 1 : 0));
}

function readSchema(path) {
  return JSON.parse(readFileSync(resolve(SCHEMAS_DIR, `${path}.json`), 'utf8'));
}

/** Resolves a relative $ref of the schema at path to the referenced schema path. */
function refTarget(path, ref) {
  if (ref.includes('#')) throw new Error(`${path}: $ref with a fragment into another file is not supported: ${ref}`);
  return posix.join(posix.dirname(path), ref).replace(/\.json$/, '');
}

/** Copy of a schema node that json-schema-to-typescript can turn into the intended type. */
function prepare(node, path) {
  if (Array.isArray(node)) return node.map((item) => prepare(item, path));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === 'if' || key === 'then' || key === 'else') continue;
    if (key === 'allOf') {
      if (!value.every((member) => 'if' in member)) throw new Error(`${path}: allOf is only supported with conditional members`);
      continue;
    }
    if (key === 'not') throw new Error(`${path}: "not" outside a conditional cannot be typed`);
    if (key === '$defs') continue; // declared as separate types by defTypes
    if (key === '$ref') {
      out.tsType = value.startsWith('#') ? defTypeName(path, value) : typeNameOf(refTarget(path, value));
      continue;
    }
    // Property names are not keywords: a property may be called "if" or "not".
    out[key] = key === 'properties'
      ? Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, prepare(sub, path)]))
      : prepare(value, path);
  }
  // json-schema-to-typescript drops the description of an anyOf member: keep it for "X | null" properties.
  const described = (node.anyOf ?? []).filter((member) => member.description);
  if (!out.description && described.length === 1) out.description = described[0].description;
  return out;
}

/** Type name of a local $ref (#/$defs/<name>): the PascalCase name of the definition. */
function defTypeName(path, ref) {
  const match = /^#\/\$defs\/([A-Za-z0-9_-]+)$/.exec(ref);
  if (!match) throw new Error(`${path}: only #/$defs/<name> local references are supported: ${ref}`);
  return pascal(match[1]);
}

/** The $defs of a schema as separate named types. */
async function defTypes(schema, path) {
  const out = [];
  for (const [name, def] of Object.entries(schema.$defs ?? {})) out.push(await compileSchema(def, path, pascal(name)));
  return out;
}

async function compileSchema(schema, path, name) {
  const input = { ...prepare(schema, path), title: name };
  delete input.$schema;
  delete input.$id;
  // Every $ref is a tsType by now, so nothing is resolved or declared besides this one type.
  const ts = await compile(input, name, { bannerComment: '', additionalProperties: false, maxItems: -1, unknownAny: true });
  return ts.trim();
}

/** chain/entry.json → ChainEntryFields + ChainEntryType + ChainPayloadMap + ChainEntryOf<T> + ChainEntry. */
async function compileEntry(schema) {
  const types = schema.properties.type.enum;
  const payloads = new Map();
  for (const member of schema.allOf) {
    const type = member.if?.properties?.type?.const;
    if (type === undefined) continue;
    const ref = member.then?.properties?.payload?.$ref;
    if (!ref || payloads.has(type)) throw new Error(`${ENTRY_PATH}: the branch of type ${type} must set exactly one payload $ref`);
    payloads.set(type, typeNameOf(refTarget(ENTRY_PATH, ref)));
  }
  const missing = types.filter((t) => !payloads.has(t));
  const extra = [...payloads.keys()].filter((t) => !types.includes(t));
  if (missing.length || extra.length) {
    throw new Error(`${ENTRY_PATH}: type enum and payload branches differ (no branch: ${missing.join(', ') || '–'}; not in enum: ${extra.join(', ') || '–'})`);
  }

  const { type: _type, payload, ...otherProperties } = schema.properties;
  const fields = {
    ...schema,
    description: 'The fields every chain entry has besides type and payload (chain/entry.json).',
    properties: otherProperties,
    required: schema.required.filter((p) => p !== 'type' && p !== 'payload'),
  };
  const comment = (text) => `/**\n${text.split('\n').map((line) => ` * ${line}`.trimEnd()).join('\n')}\n */`;
  return [
    await compileSchema(fields, ENTRY_PATH, ENTRY_FIELDS_TYPE),
    `${comment('Type of a chain entry.')}\nexport type ChainEntryType = ${types.map((t) => JSON.stringify(t)).join(' | ')};`,
    `${comment('Payload type of each chain entry type (the type → payload branches of chain/entry.json).')}
export interface ChainPayloadMap {
${types.map((t) => `  ${t}: ${payloads.get(t)};`).join('\n')}
}`,
    `${comment('A chain entry of the given type.')}
export interface ChainEntryOf<T extends ChainEntryType> extends ${ENTRY_FIELDS_TYPE} {
  type: T;
${payload.description ? `  ${comment(payload.description).split('\n').join('\n  ')}\n` : ''}  payload: ChainPayloadMap[T];
}`,
    `${comment(`${schema.description}\n\nDiscriminated union on type: narrowing on entry.type narrows entry.payload.`)}
export type ChainEntry = { [T in ChainEntryType]: ChainEntryOf<T> }[ChainEntryType];`,
  ].join('\n\n');
}

export async function renderTypes() {
  const paths = schemaPaths();
  const names = new Map();
  const claim = (name, owner) => {
    if (names.has(name)) throw new Error(`type name ${name} is used by both ${names.get(name)} and ${owner}`);
    names.set(name, owner);
  };
  for (const path of paths) {
    claim(typeNameOf(path), path);
    for (const def of Object.keys(readSchema(path).$defs ?? {})) claim(pascal(def), `${path}#/$defs/${def}`);
  }

  const sections = [];
  for (const path of paths) {
    const schema = readSchema(path);
    const expectedId = `https://waypost.dev/schema/${path}.json`;
    if (schema.$id !== expectedId) throw new Error(`${path}: $id must be ${expectedId}`);
    const main = path === ENTRY_PATH ? await compileEntry(schema) : await compileSchema(schema, path, typeNameOf(path));
    sections.push(`// ${path}.json\n\n${[main, ...(await defTypes(schema, path))].join('\n\n')}`);
  }
  sections.push(`/**
 * TypeScript type of each schema, keyed by its path under schemas/ without .json
 * (the schema's $id without https://waypost.dev/schema/ and .json).
 */
export interface SchemaTypes {
${paths.map((p) => `  ${JSON.stringify(p)}: ${typeNameOf(p)};`).join('\n')}
}`);
  return `${BANNER}\n${sections.join('\n\n')}\n`;
}

async function main(argv) {
  const content = await renderTypes();
  if (argv.includes('--check')) {
    let current = null;
    try {
      current = readFileSync(TYPES_FILE, 'utf8');
    } catch {
      // missing file is reported below
    }
    if (current !== content) {
      console.error('types/index.d.ts is out of date; run: npm run types');
      return 1;
    }
    console.log('types/index.d.ts is up to date');
    return 0;
  }
  writeFileSync(TYPES_FILE, content);
  console.log('wrote types/index.d.ts');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = await main(process.argv.slice(2));
}
