#!/usr/bin/env node
// Reference generator of pin/test-vectors.json: PIN + salt + iterations → PBKDF2-HMAC-SHA256 verifier, as
// stored in the user's pin_hash / pin_salt / pin_iterations. Deterministic: fixed salts. Usage:
//   node scripts/pin-vectors.js          write pin/test-vectors.json
//   node scripts/pin-vectors.js --check  exit 1 if the file differs from what would be written

import { pbkdf2Sync } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const VECTORS_FILE = resolve(fileURLToPath(import.meta.url), '..', '..', 'pin', 'test-vectors.json');

export const PIN_PATTERN = '^[0-9]{6}$';
export const ITERATIONS = 100_000;
export const SALT_BYTES = 16;
export const HASH_BYTES = 32;

/** pin_hash (base64) of a PIN: PBKDF2-HMAC-SHA256 over the PIN's ASCII digits, with the raw salt bytes. */
export function pinHash(pin, saltBase64, iterations) {
  if (!new RegExp(PIN_PATTERN).test(pin)) throw new Error(`malformed PIN: ${JSON.stringify(pin)}`);
  return pbkdf2Sync(Buffer.from(pin, 'ascii'), Buffer.from(saltBase64, 'base64'), iterations, HASH_BYTES, 'sha256').toString('base64');
}

const salt = (bytes) => Buffer.from(bytes).toString('base64');
const SALT_SEQUENCE = salt(Array.from({ length: SALT_BYTES }, (_, i) => i)); // 00 01 … 0f
const SALT_FF = salt(Array(SALT_BYTES).fill(0xff));
// Bytes whose standard base64 contains "+" and "/": a base64url decoder gets them wrong.
const SALT_SPECIALS = salt([0xfb, 0xef, 0xbe, 0xfb, 0xff, 0xbf, 0x3e, 0x3f, 0xfb, 0xef, 0xbe, 0xfb, 0xff, 0xbf, 0x3e, 0x3f]);

const CASES = [
  ['basic', 'The default parameters.', '123456', SALT_SEQUENCE, ITERATIONS],
  ['other-salt', 'The same PIN with another salt gives another hash.', '123456', SALT_FF, ITERATIONS],
  ['leading-zeros', 'The PIN is a string of digits, not a number: 001234 ≠ 1234.', '001234', SALT_SEQUENCE, ITERATIONS],
  ['all-zeros', 'The smallest PIN.', '000000', SALT_SEQUENCE, ITERATIONS],
  ['all-nines', 'The largest PIN.', '999999', SALT_SEQUENCE, ITERATIONS],
  ['salt-with-plus-and-slash', 'The salt is standard base64 (RFC 4648 section 4), not base64url.', '123456', SALT_SPECIALS, ITERATIONS],
  ['more-iterations', 'The iteration count comes from the stored record (pin_iterations), not from a constant.', '123456', SALT_SEQUENCE, 2 * ITERATIONS],
];

export function buildVectors() {
  const cases = CASES.map(([name, description, pin, pinSalt, iterations]) => ({
    name,
    description,
    pin,
    pin_salt: pinSalt,
    pin_iterations: iterations,
    pin_hash: pinHash(pin, pinSalt, iterations),
  }));
  const basic = cases[0];
  return {
    description: 'Waypost PIN test vectors. A PIN is 6 ASCII digits; its verifier is PBKDF2-HMAC-SHA256 over the PIN\'s bytes with the raw (base64-decoded) salt, the given iteration count and a 32-byte output, stored as base64 in pin_hash next to pin_salt and pin_iterations (entities/user). Rules: docs/decisions.md. Generated by scripts/pin-vectors.js; do not edit by hand.',
    pin_pattern: PIN_PATTERN,
    defaults: { iterations: ITERATIONS, salt_bytes: SALT_BYTES, hash_bytes: HASH_BYTES },
    cases,
    mismatches: [
      ['neighbour-pin', 'A PIN one digit off.', '123457'],
      ['reversed-pin', 'The same digits in another order.', '654321'],
    ].map(([name, description, pin]) => ({
      name,
      description,
      pin,
      pin_salt: basic.pin_salt,
      pin_iterations: basic.pin_iterations,
      pin_hash: basic.pin_hash,
    })),
    malformed_pins: ['12345', '1234567', '', '12345a', ' 123456', '123456 ', '123456\n', '12 456', '١٢٣٤٥٦', '１２３４５６'],
  };
}

export function renderVectors() {
  return `${JSON.stringify(buildVectors(), null, 2)}\n`;
}

function main(argv) {
  const content = renderVectors();
  if (argv.includes('--check')) {
    let current = null;
    try {
      current = readFileSync(VECTORS_FILE, 'utf8');
    } catch {
      // missing file is reported below
    }
    if (current !== content) {
      console.error('pin/test-vectors.json is out of date; run: npm run vectors:pin');
      return 1;
    }
    console.log('pin/test-vectors.json is up to date');
    return 0;
  }
  writeFileSync(VECTORS_FILE, content);
  console.log('wrote pin/test-vectors.json');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
