#!/usr/bin/env node
// Embeds the schemas and the test vectors as plain ES modules in lib/generated/, so they can be imported in
// every JS runtime, including React Native (Metro), which cannot import JSON with import attributes.
// Deterministic. Usage:
//   node scripts/embed.js          write lib/generated/*.js
//   node scripts/embed.js --check  exit 1 if a file differs from what would be written

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { schemaPaths } from './types.js';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const GENERATED_DIR = resolve(ROOT, 'lib', 'generated');

const readJson = (path) => JSON.parse(readFileSync(resolve(ROOT, path), 'utf8'));

// U+2028 and U+2029 are escaped: valid in string literals only since ES2019.
const module = (source, value) => `// Generated by scripts/embed.js from ${source}. Do not edit; run: npm run embed

export default ${JSON.stringify(value, null, 2).replace(/[\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16)}`)};
`;

/** File name under lib/generated/ → content. */
export function renderEmbedded() {
  const schemas = Object.fromEntries(schemaPaths().map((path) => [path, readJson(`schemas/${path}.json`)]));
  return {
    'schemas.js': module('schemas/**/*.json', schemas),
    'chain-vectors.js': module('chain/test-vectors.json', readJson('chain/test-vectors.json')),
    'schedule-vectors.js': module('schedule/test-vectors.json', readJson('schedule/test-vectors.json')),
    'pin-vectors.js': module('pin/test-vectors.json', readJson('pin/test-vectors.json')),
  };
}

function main(argv) {
  const files = Object.entries(renderEmbedded());
  if (argv.includes('--check')) {
    const stale = files.filter(([name, content]) => {
      try {
        return readFileSync(resolve(GENERATED_DIR, name), 'utf8') !== content;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`lib/generated/ is out of date (${stale.map(([name]) => name).join(', ')}); run: npm run embed`);
      return 1;
    }
    console.log('lib/generated/ is up to date');
    return 0;
  }
  for (const [name, content] of files) writeFileSync(resolve(GENERATED_DIR, name), content);
  console.log(`wrote lib/generated/ (${files.map(([name]) => name).join(', ')})`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
